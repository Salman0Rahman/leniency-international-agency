<script>
    (function () {
        var root = document.querySelector(".lia-network");
        if (!root || root.getAttribute("data-lia-init")) return;
        root.setAttribute("data-lia-init", "1");
        var dlg = root.querySelector(".lia-dialog");
        var body = root.querySelector(".lia-dialog-body");

        // One click handler for the whole section; it always reads the card that was clicked.
        root.addEventListener("click", function (e) {
          var t = e.target.closest(".lia-view, .lia-frame");
          if (!t || !dlg.showModal) return;
          // The frame itself, or the frame right before the clicked button.
          // This way a card with 2 or more certificates opens the correct one.
          var frame = t.classList.contains("lia-frame")
            ? t
            : t.previousElementSibling;
          var im = frame && frame.querySelector && frame.querySelector("img");
          if (!im) return; // image not uploaded yet
          var big = new Image(); // fresh image every time, so an old one never shows again
          big.alt = im.alt;
          big.src = im.currentSrc || im.src;
          body.innerHTML = "";
          body.appendChild(big);
          if (!dlg.open) dlg.showModal();
        });

        dlg.addEventListener("click", function (e) {
          if (e.target === dlg) dlg.close();
        });
        dlg.addEventListener("close", function () {
          body.innerHTML = "";
        });
      })();
</script>
@endpush